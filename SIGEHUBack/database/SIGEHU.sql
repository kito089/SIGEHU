--   7. Vistas (dashboard, móvil, búsqueda)
--
-- Convención de sesión (obligatoria desde Node.js antes de cada transacción):
--   SELECT RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_USER_ID', :idTrabajador)
--       FROM RDB$DATABASE;
--
-- Auditoría en UPDATE:
--   Los triggers registran solo la cabecera en Auditorias y publican
--   LAST_AUDIT_ID en contexto de sesión. El backend compara valores y
--   persiste AuditoriasDetalles con SP_INSERTAR_AUDITORIA_DETALLE.
