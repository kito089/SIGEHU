    m.idMaterial,
    m.Nombre                  AS NombreMaterial,
    m.UnidadMedida,
    km.Cantidad,
    km.Notas
FROM Kits_has_Materiales km
JOIN Kits_Instalacion k ON k.idKit = km.Kits_Instalacion_idKit
JOIN Materiales m       ON m.idMaterial = km.Materiales_idMaterial
WHERE k.Activo = TRUE
  AND m.Activo = TRUE;

-- -----------------------------------------------------------------------------
-- VW_CHECKLIST_KIT_OBRA
-- Checklist interactivo de un kit asignado a una obra (RF-23).
-- El backend filtra por Obras_idObra o idObraKit.
-- -----------------------------------------------------------------------------
CREATE OR ALTER VIEW VW_CHECKLIST_KIT_OBRA AS
SELECT
    ok.idObraKit,
    ok.Obras_idObra,
    ok.Kits_Instalacion_idKit AS idKit,
    k.Nombre                  AS NombreKit,
    ok.FechaAsignacion,
    cl.idChecklistItem,
    cl.Materiales_idMaterial,
    m.Nombre                  AS NombreMaterial,
    m.UnidadMedida,
    cl.Marcado,
    cl.FechaMarcado,
    cl.Trabajadores_idTrabajador AS IdTrabajadorQueMarco
FROM Obras_has_Kits ok
JOIN Kits_Instalacion k ON k.idKit = ok.Kits_Instalacion_idKit
JOIN Obras_Kits_Checklist cl ON cl.Obras_has_Kits_idObraKit = ok.idObraKit
JOIN Materiales m ON m.idMaterial = cl.Materiales_idMaterial;

