// Aplicador idempotente de la migración FechaInicio en Obras + vínculo a TRABAJO.
// Uso: node src/scripts/apply-obra-fecha-inicio-migration.js
// Verifica cada objeto (tabla/columna) contra RDB$ antes de crearlo y re-crea
// con CREATE OR ALTER el SP_INSERTAR_OBRA ampliado.
import { getConnection, disconnectDB } from "../config/db.js";

const STEPS = [
    {
        name: "Tabla TRABAJO",
        check: `SELECT 1 FROM RDB$RELATIONS
                WHERE RDB$RELATION_NAME = 'TRABAJO'`,
        create: `CREATE TABLE TRABAJO (
            idTrabajo INTEGER GENERATED BY DEFAULT AS IDENTITY,
            Nombre VARCHAR(100) NOT NULL,
            Descripcion BLOB SUB_TYPE TEXT,
            Direccion BLOB SUB_TYPE TEXT,
            FechaCreacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            Clientes_idCliente INTEGER NOT NULL,
            PRIMARY KEY (idTrabajo),
            CONSTRAINT fk_TRABAJO_Clientes1
                FOREIGN KEY (Clientes_idCliente)
                REFERENCES Clientes (idCliente)
                    ON DELETE NO ACTION
        )`
    },
    {
        name: "Índice fk_TRABAJO_Clientes1_idx",
        check: `SELECT 1 FROM RDB$INDICES
                WHERE RDB$INDEX_NAME = 'FK_TRABAJO_CLIENTES1_IDX'`,
        create: `CREATE INDEX fk_TRABAJO_Clientes1_idx ON TRABAJO(Clientes_idCliente)`
    },
    {
        name: "Columna TRABAJOS_IDTRABAJO en Obras",
        check: `SELECT 1 FROM RDB$RELATION_FIELDS
                WHERE RDB$RELATION_NAME = 'OBRAS'
                  AND RDB$FIELD_NAME = 'TRABAJOS_IDTRABAJO'`,
        create: `ALTER TABLE Obras ADD TRABAJOS_IDTRABAJO INTEGER`
    },
    {
        name: "Columna FechaInicio en Obras",
        check: `SELECT 1 FROM RDB$RELATION_FIELDS
                WHERE RDB$RELATION_NAME = 'OBRAS'
                  AND RDB$FIELD_NAME = 'FECHAINICIO'`,
        create: `ALTER TABLE Obras ADD FechaInicio TIMESTAMP`
    },
    {
        name: "FK fk_Obras_TRABAJO1",
        check: `SELECT 1 FROM RDB$RELATION_CONSTRAINTS
                WHERE RDB$CONSTRAINT_NAME = 'FK_OBRAS_TRABAJO1'
                  AND RDB$CONSTRAINT_TYPE = 'FOREIGN KEY'`,
        create: `ALTER TABLE Obras ADD CONSTRAINT fk_Obras_TRABAJO1
                 FOREIGN KEY (TRABAJOS_IDTRABAJO)
                 REFERENCES TRABAJO (idTrabajo)
                     ON DELETE NO ACTION`
    }
];

// El SP se re-crea SIEMPRE con CREATE OR ALTER (idempotente por diseño), ya
// que el check de existencia no detectaría una firma desactualizada.
const SP_SQL = `CREATE OR ALTER PROCEDURE SP_INSERTAR_OBRA (
    pIdCliente INTEGER,
    pNombre    VARCHAR(100),
    pDireccion BLOB SUB_TYPE TEXT,
    pIdTrabajo INTEGER,
    pFechaInicio TIMESTAMP,
    pAncho     DECIMAL(10,2),
    pAlto      DECIMAL(10,2),
    pProfundidad DECIMAL(10,2)
)
RETURNS (
    oIdObra INTEGER
)
AS
BEGIN
    INSERT INTO Obras (Clientes_idCliente, Nombre, Direccion, TRABAJOS_IDTRABAJO, FechaInicio, Ancho, Alto, Profundidad, EstadosObra_idEstadoObra)
    VALUES (:pIdCliente, :pNombre, :pDireccion, :pIdTrabajo, :pFechaInicio, :pAncho, :pAlto, :pProfundidad, 1)
    RETURNING idObra INTO :oIdObra;

    SUSPEND;
END`;

async function main() {
    const db = await getConnection();
    let creados = 0;

    for (const step of STEPS) {
        const existe = await db.query(step.check, []);
        if (existe && existe.length > 0) {
            console.log(`[migración] Ya existe: ${step.name}`);
            continue;
        }
        await db.execute(step.create, []);
        creados += 1;
        console.log(`[migración] Creado: ${step.name}`);
    }

    console.log("[migración] Actualizando SP_INSERTAR_OBRA (CREATE OR ALTER)...");
    await db.execute(SP_SQL, []);

    await disconnectDB();
    console.log(`[migración] Completado. Objetos creados: ${creados}`);
    process.exit(0);
}

main().catch((err) => {
    console.error("[migración] Error:", err?.message || err);
    process.exit(1);
});