// Aplicador idempotente de la migración del centro de notificaciones.
// Uso: node src/scripts/apply-notificaciones-migration.js
// Verifica cada objeto (tabla/índice) contra RDB$ antes de crearlo.
import { getConnection, disconnectDB } from "../config/db.js";

const STEPS = [
    {
        name: "Tabla NOTIFICACIONES",
        check: "SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'NOTIFICACIONES'",
        create: `CREATE TABLE Notificaciones (
            IdNotificacion INTEGER GENERATED BY DEFAULT AS IDENTITY,
            Trabajadores_idTrabajador INTEGER NOT NULL,
            Tipo VARCHAR(12) NOT NULL,
            Mensaje VARCHAR(500) NOT NULL,
            CreadoEn TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            PRIMARY KEY (IdNotificacion),
            CONSTRAINT fk_Notificaciones_Trabajadores1
                FOREIGN KEY (Trabajadores_idTrabajador)
                REFERENCES Trabajadores (idTrabajador)
                    ON DELETE NO ACTION
        )`
    },
    {
        name: "Índice IDX_Notificaciones_Trabajador_CreadoEn",
        check: `SELECT 1 FROM RDB$INDICES
                WHERE RDB$INDEX_NAME = 'IDX_NOTIFICACIONES_TRABAJADOR_CREADOEN'`,
        create: `CREATE DESCENDING INDEX IDX_Notificaciones_Trabajador_CreadoEn
                 ON Notificaciones (Trabajadores_idTrabajador, CreadoEn)`
    }
];

async function main() {
    const db = await getConnection();
    let creados = 0;

    for (const step of STEPS) {
        const existe = await db.query(step.check, []);
        if (existe && existe.length > 0) {
            console.log(`[migración] Ya existe: ${step.name}`);
            continue;
        }
        await db.execute(step.create, []);
        creados += 1;
        console.log(`[migración] Creado: ${step.name}`);
    }

    await disconnectDB();
    console.log(`[migración] Completado. Objetos creados: ${creados}`);
    process.exit(0);
}

main().catch((err) => {
    console.error("[migración] Error:", err?.message || err);
    process.exit(1);
});